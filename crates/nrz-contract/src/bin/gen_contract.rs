use std::path::PathBuf;

use anyhow::{Context, Result};
use quote::quote;
use schemars08::schema::RootSchema;
use typify::{TypeSpace, TypeSpaceSettings};

const SCHEMAS: &[(&str, &str)] = &[
    ("onreza-rules-v1", "edge_rules"),
    ("manifest-v1", "manifest"),
    ("runtime-artifact-graph-v2", "runtime_artifact_graph"),
];

fn main() -> Result<()> {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let (schema_dir, check, import) = arguments(&manifest)?;

    let mut modules = proc_macro2::TokenStream::new();

    for (slug, module) in SCHEMAS {
        let path = schema_dir.join(format!("{slug}.schema.json"));
        let content =
            std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
        let snapshot = manifest.join("schemas").join(format!("{slug}.schema.json"));
        if import {
            if check {
                anyhow::ensure!(
                    std::fs::read(&snapshot)? == content.as_bytes(),
                    "contract input drift: {slug}"
                );
            } else {
                std::fs::write(&snapshot, &content)?;
            }
        }
        let mut value: serde_json::Value =
            serde_json::from_str(&content).with_context(|| format!("parse {slug}"))?;
        normalize_for_typify(&mut value);
        let root: RootSchema = serde_json::from_value(value)
            .with_context(|| format!("deserialize root schema {slug}"))?;

        let mut settings = TypeSpaceSettings::default();
        settings.with_derive("PartialEq".to_string());
        let mut type_space = TypeSpace::new(&settings);
        type_space
            .add_root_schema(root)
            .with_context(|| format!("typify {slug}"))?;

        let body = type_space.to_stream();
        let module_ident = syn::Ident::new(module, proc_macro2::Span::call_site());
        modules.extend(quote! {
            pub mod #module_ident {
                #body
            }
        });
    }

    let file: syn::File = syn::parse2(quote! {
        #![allow(dead_code, unused, clippy::all)]
        #modules
    })
    .context("parse generated token stream")?;
    let pretty = prettyplease::unparse(&file);

    let header = "// @generated by gen-contract from the committed schemas directory.\n// Do not edit; run cargo run -p nrz-contract --features codegen --bin gen-contract.\n\n";
    let source = format!("{header}{pretty}");
    let mut formatter = std::process::Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()
        .context("start rustfmt")?;
    use std::io::Write as _;
    formatter
        .stdin
        .take()
        .context("rustfmt stdin missing")?
        .write_all(source.as_bytes())?;
    let output = formatter
        .wait_with_output()
        .context("format generated Rust")?;
    anyhow::ensure!(output.status.success(), "rustfmt failed");
    let dest = manifest.join("src/generated.rs");
    if check {
        anyhow::ensure!(
            std::fs::read(&dest)? == output.stdout,
            "generated contract drift; run gen-contract"
        );
    } else {
        std::fs::write(&dest, output.stdout)
            .with_context(|| format!("write {}", dest.display()))?;
    }
    println!(
        "{} {}",
        if check { "verified" } else { "wrote" },
        dest.display()
    );
    Ok(())
}

fn arguments(manifest: &std::path::Path) -> Result<(PathBuf, bool, bool)> {
    let mut directory = manifest.join("schemas");
    let mut check = false;
    let mut import = false;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--from" => {
                directory = args
                    .next()
                    .context("--from requires an exported schema directory")?
                    .into();
                import = true;
            }
            _ => anyhow::bail!("unknown argument: {arg}"),
        }
    }
    Ok((directory, check, import))
}

/// typify (schemars 0.8) consumes the draft-07 schema model, while the Zod
/// pipeline emits draft-2020-12. Move `$defs` to `definitions` and rewrite the
/// matching `$ref` targets so reused types resolve to named definitions.
fn normalize_for_typify(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Object(map) => {
            if let Some(defs) = map.remove("$defs") {
                map.insert("definitions".to_string(), defs);
            }
            if let Some(serde_json::Value::String(reference)) = map.get_mut("$ref")
                && let Some(rest) = reference.strip_prefix("#/$defs/")
            {
                *reference = format!("#/definitions/{rest}");
            }
            if let Some(prefix_items) = map.remove("prefixItems") {
                let additional_items = match map.remove("items") {
                    Some(serde_json::Value::Bool(false)) => Some(serde_json::Value::Bool(false)),
                    Some(serde_json::Value::Bool(true)) | None => None,
                    Some(schema) => Some(schema),
                };
                map.insert("items".to_string(), prefix_items);
                if let Some(additional_items) = additional_items {
                    map.insert("additionalItems".to_string(), additional_items);
                }
            }
            for child in map.values_mut() {
                normalize_for_typify(child);
            }
        }
        serde_json::Value::Array(items) => {
            for item in items {
                normalize_for_typify(item);
            }
        }
        _ => {}
    }
}


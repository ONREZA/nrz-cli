use std::path::PathBuf;

use anyhow::{Context, Result};
use nrz_contract::codegen::{SchemaDocument, generate};

const SCHEMAS: &[(&str, &str)] = &[
    ("onreza-rules-v1", "edge_rules"),
    ("manifest-v1", "manifest"),
    ("runtime-artifact-graph-v2", "runtime_artifact_graph"),
];

fn main() -> Result<()> {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let (schema_dir, check, import) = arguments(&manifest)?;

    let contents: Vec<String> = SCHEMAS
        .iter()
        .map(|(slug, _)| {
            let path = schema_dir.join(format!("{slug}.schema.json"));
            std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))
        })
        .collect::<Result<_>>()?;
    let documents: Vec<_> = SCHEMAS
        .iter()
        .zip(&contents)
        .map(|((_, module), content)| SchemaDocument {
            module,
            schema: content,
            embedded_constant: None,
        })
        .collect();
    let header = "// @generated by gen-contract from the committed schemas directory.\n// Do not edit; run cargo run -p nrz-contract --features codegen --bin gen-contract.\n\n";
    let source = generate(&documents, header)?;
    if import {
        for ((slug, _), content) in SCHEMAS.iter().zip(&contents) {
            let snapshot = manifest.join("schemas").join(format!("{slug}.schema.json"));
            if check {
                anyhow::ensure!(
                    std::fs::read(&snapshot)? == content.as_bytes(),
                    "contract input drift: {slug}"
                );
            } else {
                std::fs::write(&snapshot, content)
                    .with_context(|| format!("write {}", snapshot.display()))?;
            }
        }
    }
    if import {
        // Public toolchain projections share the canonical schema export owner.
        // Standalone CLI builds consume committed copies without a platform checkout.
        let public = schema_dir
            .parent()
            .context("schema export has no public parent")?;
        for (name, destination) in [
            (
                "runtime-toolchains.json",
                manifest.join("../nrz-source-bundle/assets/runtime-toolchains.json"),
            ),
            (
                "native-toolchains.json",
                manifest.join("../../assets/native-toolchains.json"),
            ),
        ] {
            let source = public.join(name);
            let bytes =
                std::fs::read(&source).with_context(|| format!("read {}", source.display()))?;
            if check {
                anyhow::ensure!(
                    std::fs::read(&destination)? == bytes,
                    "public toolchain projection drift: {name}"
                );
            } else {
                std::fs::create_dir_all(
                    destination
                        .parent()
                        .context("toolchain projection has no directory")?,
                )?;
                std::fs::write(&destination, bytes)
                    .with_context(|| format!("write {}", destination.display()))?;
            }
        }
    }
    let dest = manifest.join("src/generated.rs");
    if check {
        anyhow::ensure!(
            std::fs::read(&dest)? == source.as_bytes(),
            "generated contract drift; run gen-contract"
        );
    } else {
        std::fs::write(&dest, source).with_context(|| format!("write {}", dest.display()))?;
    }
    println!(
        "{} {}",
        if check { "verified" } else { "wrote" },
        dest.display()
    );
    Ok(())
}

fn arguments(manifest: &std::path::Path) -> Result<(PathBuf, bool, bool)> {
    let mut directory = manifest.join("schemas");
    let mut check = false;
    let mut import = false;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--from" => {
                directory = args
                    .next()
                    .context("--from requires an exported schema directory")?
                    .into();
                import = true;
            }
            _ => anyhow::bail!("unknown argument: {arg}"),
        }
    }
    Ok((directory, check, import))
}

import os
import site
import sys


def onreza_add_site_packages(directory, source_paths=()):
    """Initialize one installed dependency tree before application sources."""
    directory = os.path.realpath(os.fspath(directory))
    source_paths = [os.fspath(path) for path in source_paths]

    def canonical(path):
        return os.path.realpath(path) if isinstance(path, str) else None

    processed = site.__dict__.setdefault("_onreza_site_packages", {})
    dependency_paths = processed.get(directory)
    if dependency_paths is None:
        excluded = {canonical(path) for path in source_paths}
        excluded.add(directory)
        # Hooks may import the installed application itself. Source fallbacks
        # must not populate sys.modules before the wheel's .pth paths exist.
        sys.path[:] = [directory] + [
            path for path in sys.path if canonical(path) not in excluded
        ]
        previous = {canonical(path) for path in sys.path}
        # Ask stdlib to record every .pth directory, including directories that
        # were already on sys.path before this installed tree was initialized.
        known_paths = set()
        site.addsitedir(directory, known_paths)
        site_paths = {canonical(path) for path in known_paths}
        dependency_paths = [directory] + [
            path for path in sys.path
            if isinstance(path, str)
            and (canonical(path) in site_paths or canonical(path) not in previous)
        ]
        # Stored on stdlib site so a script wrapper and its generated bootstrap
        # can execute this definition without running import hooks twice.
        processed[directory] = dependency_paths

    leading = []
    leading_keys = set()
    for path in [*dependency_paths, *source_paths]:
        key = canonical(path)
        if key not in leading_keys:
            leading.append(path)
            leading_keys.add(key)
    sys.path[:] = leading + [
        path for path in sys.path if canonical(path) not in leading_keys
    ]
